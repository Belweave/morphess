import { readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { Resvg } from '@resvg/resvg-js';

// Crop Morph's official docs logo, preserving its emblem geometry. Integrate
// alpha over each terminal character cell instead of inventing a new mark.
const svg = await readFile(new URL('../assets/brand/morph-official.svg', import.meta.url), 'utf8');
const cropped = svg.replace('width="185" height="57" viewBox="0 0 185 57"', 'width="48" height="40" viewBox="0 8 48 40"');
const raster = new Resvg(cropped, { fitTo: { mode: 'width', value: 280 } }).render();
const pixels = raster.pixels;
function ascii(width: number, height: number): string {
  const ramp = ' .:-=+*#%@';
  const lines: string[] = [];
  for (let row = 0; row < height; row++) {
    let line = '';
    for (let column = 0; column < width; column++) {
      let sum = 0; let samples = 0;
      for (let y = Math.floor(row * raster.height / height); y < Math.floor((row + 1) * raster.height / height); y++) {
        for (let x = Math.floor(column * raster.width / width); x < Math.floor((column + 1) * raster.width / width); x++) {
          sum += pixels[(y * raster.width + x) * 4 + 3]!; samples++;
        }
      }
      line += ramp[Math.min(ramp.length - 1, Math.round(sum / Math.max(1, samples) / 255 * (ramp.length - 1)))];
    }
    lines.push(line.trimEnd());
  }
  return lines.join('\n').trimEnd();
}
await writeFile(new URL('../src/tui/brand.ts', import.meta.url), `// Generated by npm run brand from assets/brand/morph-official.svg. Do not redraw by hand.\nexport const MORPH_MARK = ${JSON.stringify(ascii(28, 12))};\nexport const MORPH_MARK_SMALL = ${JSON.stringify(ascii(14, 6))};\nexport const MORPH_GREEN = '#00eb81';\nexport const MORPH_SOURCE_SHA256 = '${createHash('sha256').update(svg).digest('hex')}';\n`);
